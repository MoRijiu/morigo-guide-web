// Extract only the icons actually used in src/ from the @iconify-json data
// packages and generate src/icons/localIcons.ts, which registers them with
// addIcon() so @iconify/vue renders fully offline (no api.iconify.design
// runtime fetch — that API is slow/unreachable for many CN users, which left
// every card icon blank).
// Re-run after adding a new icon name anywhere in src/:  node scripts/gen-icons.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else if (/\.(vue|ts)$/.test(name)) yield p
  }
}

const used = new Set()
const re = /([a-z0-9-]+):([a-z0-9-]+)/g
for (const file of walk(join(root, 'src'))) {
  const text = readFileSync(file, 'utf8')
  for (const m of text.matchAll(re)) used.add(`${m[1]}:${m[2]}`)
}

const byPrefix = new Map()
for (const full of used) {
  const [prefix, name] = full.split(':')
  if (!byPrefix.has(prefix)) byPrefix.set(prefix, new Set())
  byPrefix.get(prefix).add(name)
}

const entries = []
const missing = []
for (const [prefix, names] of byPrefix) {
  let data
  try {
    data = JSON.parse(readFileSync(join(root, 'node_modules', '@iconify-json', prefix, 'icons.json'), 'utf8'))
  } catch {
    continue // not an icon prefix (e.g. "https:" style false positives)
  }
  for (const name of names) {
    const icon = data.icons[name]
    if (!icon) { missing.push(`${prefix}:${name}`); continue }
    const { hidden, ...rest } = icon
    entries.push({ full: `${prefix}:${name}`, data: { ...rest, width: data.width, height: data.height } })
  }
}

if (missing.length) {
  console.error('Icons not found in data packages:', missing.join(', '))
  process.exit(1)
}

entries.sort((a, b) => a.full.localeCompare(b.full))
const body = entries
  .map(e => `addIcon(${JSON.stringify(e.full)}, ${JSON.stringify(e.data)})`)
  .join('\n')

mkdirSync(join(root, 'src/icons'), { recursive: true })
writeFileSync(join(root, 'src/icons/localIcons.ts'), `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Registers every icon used in src/ locally so @iconify/vue never fetches
// api.iconify.design at runtime. Re-run the script after adding new icons.
import { addIcon } from '@iconify/vue'

${body}
`)
console.log(`Wrote ${entries.length} icons: ${entries.map(e => e.full).join(', ')}`)
