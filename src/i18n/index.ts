function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === 'zh' || saved === 'en' || saved === 'ja') return saved
  } catch {
    // 存储不可用时仅按浏览器语言猜测
  }
  if (typeof navigator === 'undefined') return 'zh'
  const nav = navigator.language.toLowerCase()
  if (nav.startsWith('ja')) return 'ja'
  return nav.startsWith('en') ? 'en' : 'zh'
}

const locale = ref<Locale>(detectLocale())

/** 独立导出的翻译函数（工具层如 dataTransfer 也要给用户看报错文案） */
export function t(key: string, params?: Record<string, string | number>): string {
  let text = messages[locale.value][key] ?? messages.zh[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v))
    }
  }
  return text
}

function applyLocale() {
  if (typeof document === 'undefined') return
  document.documentElement.lang = locale.value === 'zh' ? 'zh-CN' : locale.value
  document.title = `MoriGo - ${t('app.tagline')}`
}

/** 在应用挂载前调用一次，落 <html lang> 与标题 */
export function initLocale() {
  applyLocale()
}

